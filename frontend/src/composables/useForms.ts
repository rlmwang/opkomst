export const formList = listOf<FormListOut>;
export const useArchivedForms = formsApi.useArchived;
export const useForm = formsApi.useSingle;
export const useFormSummary = formsApi.useSummary;
export const fetchFormSubmissions = formsApi.fetchSubmissions;
export const usePublicForm = formsApi.usePublic;
export const useCreateForm = formsApi.useCreate;
export const useUpdateForm = formsApi.useUpdate;
export const useArchiveForm = formsApi.useArchive;
export const useRestoreForm = formsApi.useRestore;
export const useDeleteForm = formsApi.useDelete;
export const useSubmitForm = formsApi.useSubmit;
